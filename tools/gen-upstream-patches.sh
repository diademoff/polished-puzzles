#!/bin/sh
# Writes app/src/main/jni/UPSTREAM-PATCHES.txt.
#
# The file records the Android patch layer: every vendored file whose
# content differs from the upstream commit in UPSTREAM.lock. The patch
# layer is part of the baseline (see docs/DEVIATIONS.md, D-001).
#
# A file that starts to differ, or stops differing, changes this list.
# That is a deliberate act: review the diff and update the file with
# this script in the same change.
#
# Needs the upstream commit in the local clone (git fetch simon).

set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
JNI="$ROOT/app/src/main/jni"
MANIFEST="$JNI/UPSTREAM-FILES.txt"
OUT="$JNI/UPSTREAM-PATCHES.txt"
LOCK="$ROOT/UPSTREAM.lock"

COMMIT=$(sed -n 's/^  commit: "\([0-9a-f]\{40\}\)"$/\1/p' "$LOCK" | head -1)
[ -n "$COMMIT" ] || { echo "gen-upstream-patches.sh: UPSTREAM.lock has no commit" >&2; exit 2; }
git -C "$ROOT" cat-file -e "$COMMIT^{commit}" 2>/dev/null || {
    echo "gen-upstream-patches.sh: commit $COMMIT is not in this clone; run: git fetch simon" >&2
    exit 2
}

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
: > "$TMP"

grep '^[0-9a-f]' "$MANIFEST" | awk '{ print $2 }' | while IFS= read -r path; do
    upstream=$(git -C "$ROOT" rev-parse "$COMMIT:$path" 2>/dev/null) || continue
    current=$(git -C "$ROOT" hash-object -- "$JNI/$path")
    if [ "$upstream" != "$current" ]; then
        stats=$(git -C "$ROOT" diff --numstat "$upstream" "$current" | cut -f1,2)
        printf '%s\t%s\n' "$path" "$stats"
    fi
done | sort > "$TMP"

{
    echo "# Files in app/src/main/jni that differ from upstream."
    echo "#"
    echo "# Generated by tools/gen-upstream-patches.sh. Do not edit by hand."
    echo "#"
    echo "# Upstream commit: $COMMIT"
    echo "#"
    echo "# This is the Android patch layer, recorded as the Phase 0"
    echo "# baseline; see docs/DEVIATIONS.md, D-001."
    echo "# Format: path <TAB> added <TAB> removed"
    cat "$TMP"
} > "$OUT"

echo "wrote $OUT ($(grep -c '	' "$OUT") files)"
