#!/bin/sh
# Regenerates app/src/main/jni/UPSTREAM-FILES.txt.
#
# The file is the vendored allowlist with a sha256 per file. Any change
# to a vendored file fails tools/check-upstream-diff.sh until this
# script runs again, so an edit cannot slip in unnoticed.
#
# Only tracked files are listed. Add the file to git before you
# regenerate the manifest; an untracked file stays visible to
# check-upstream-diff.sh, which is the point.
#
# Run this after an upstream sync or an approved vendored change, and
# review the diff of UPSTREAM-FILES.txt before you commit it.

set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
JNI="$ROOT/app/src/main/jni"
OUT="$JNI/UPSTREAM-FILES.txt"
LOCK="$ROOT/UPSTREAM.lock"

# Files in jni/ that are project code, not upstream code. This list must
# match the "Code ownership" table in docs/ARCHITECTURE.md.
EXCLUDES="$ROOT/tools/vendored-project-files.txt"

UPSTREAM_REPO=$(sed -n 's/^  repo: "\(.*\)"$/\1/p' "$LOCK" | head -1)
UPSTREAM_COMMIT=$(awk '
    /^upstream:$/ { section = 1; next }
    /^[a-z]+:$/ { section = 0 }
    section && /^  commit: "/ {
        value = $0
        sub(/^  commit: "/, "", value)
        sub(/".*$/, "", value)
        print value
        exit
    }
' "$LOCK")
[ -n "$UPSTREAM_REPO" ] || UPSTREAM_REPO="https://git.tartarus.org/simon/puzzles.git"
[ -n "$UPSTREAM_COMMIT" ] || UPSTREAM_COMMIT="UNSET"

[ -f "$EXCLUDES" ] || { echo "gen-vendored-manifest.sh: missing $EXCLUDES" >&2; exit 2; }

if command -v sha256sum >/dev/null 2>&1; then
    SHA256="sha256sum"
elif command -v shasum >/dev/null 2>&1; then
    SHA256="shasum -a 256"
else
    echo "gen-vendored-manifest.sh: need sha256sum or shasum" >&2
    exit 2
fi

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

if ! FILES=$(git -C "$JNI" ls-files); then
    echo "gen-vendored-manifest.sh: $JNI is not a git checkout" >&2
    exit 2
fi

printf '%s\n' "$FILES" \
    | grep -vxF -f "$EXCLUDES" \
    | grep -vx 'UPSTREAM-FILES.txt' \
    | grep -vx 'UPSTREAM-PATCHES.txt' \
    | sort > "$TMP"

{
    echo "# Vendored files in app/src/main/jni."
    echo "#"
    echo "# Generated by tools/gen-vendored-manifest.sh. Do not edit by hand."
    echo "#"
    echo "# Upstream: $UPSTREAM_REPO"
    echo "# Upstream commit: $UPSTREAM_COMMIT"
    echo "#"
    echo "# Format: sha256sum output, paths relative to this directory."
    echo "# A file here that is not listed is project code."
    echo "# Files that differ from upstream are listed in UPSTREAM-PATCHES.txt"
    echo "# (the Android patch layer, docs/DEVIATIONS.md D-001)."
    echo "#"
    echo "# tools/check-upstream-diff.sh fails when a listed file changes."

    while IFS= read -r path; do
        (cd "$JNI" && $SHA256 "$path")
    done < "$TMP"
} > "$OUT"

echo "wrote $OUT ($(grep -c '^[0-9a-f]' "$OUT") files)"
